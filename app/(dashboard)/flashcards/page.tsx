import type { Metadata } from "next";
import { getClusters } from "@/features/clusters/actions/clusters.actions";
import { getFlashcards } from "@/features/flashcards/actions/flashcards.actions";
import FlashcardsPage from "@/features/flashcards/components/flashcards";

export const metadata: Metadata = {
  title: "Flashcards — Nucleus",
  description: "Spaced repetition, generated by AI.",
};

export default async function Page({
  searchParams,
}: {
  searchParams: Promise<{ new?: string; review?: string }>;
}) {
  const { new: newParam, review } = await searchParams;
  const [cardsResult, clustersResult] = await Promise.all([
    getFlashcards(),
    getClusters(),
  ]);

  return (
    <FlashcardsPage
      initialCards={cardsResult.data ?? []}
      initialClusters={clustersResult.data ?? []}
      autoOpenCreate={newParam === "card"}
      autoStartReview={review === "due"}
    />
  );
}
